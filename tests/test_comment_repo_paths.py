"""Tests for py_ci_shared.comment_repo_paths."""

from __future__ import annotations

from pathlib import Path

import pytest

from py_ci_shared.comment_repo_paths import assert_comment_repo_paths, find_comment_repo_path_problems

BOM = b"\xef\xbb\xbf"
PUBSPEC = b"name: app\n# The core pin is checked by tool/check-core-pin.sh before a release.\nversion: 1.0.0\n"


def _corpus(tmp_path: Path, files: dict[str, bytes]) -> Path:
    for rel, data in files.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_bytes(data)
    return tmp_path


def _found(root: Path) -> list[tuple[str, int, str]]:
    return [(f.path, f.line, f.message) for f in find_comment_repo_path_problems(root, use_git=False)]


def test_reports_the_seeded_violation(tmp_path):
    root = _corpus(tmp_path, {"pubspec.yaml": PUBSPEC})
    assert _found(root) == [("pubspec.yaml", 2, "names `tool/check-core-pin.sh`, which does not exist under the repo root")]
    with pytest.raises(BaseException, match=r"tool/check-core-pin.sh"):
        assert_comment_repo_paths(root, use_git=False)


def test_negative_control_the_nearest_correct_code_is_not_reported(tmp_path):
    root = _corpus(tmp_path, {"pubspec.yaml": PUBSPEC, "tool/check-core-pin.sh": b"#!/bin/sh\nexit 0\n"})
    assert _found(root) == []
    assert_comment_repo_paths(root, use_git=False)


@pytest.mark.parametrize(
    ("rel", "text"),
    [
        ("run.sh", b"#!/bin/sh\n# see scripts/gone.py.\necho hi\n"),
        ("Dockerfile", b"FROM x\n  # built by tools/gone/build.sh,\n"),
        ("lib/main.dart", b"/// Generated by tool/gone.dart\nvoid main() {}\n"),
        ("web/app.ts", b"// run .githooks/gone first\n"),
        ("ci.toml", b"# .github/scripts/gone.py: the guard\n"),
        ("mod.py", b'"""Docstring cites tool/gone.py."""\nx = 1  # and tool/also_gone.py\n'),
        ("tool/hook", b"#!/bin/sh\n# calls tool/gone.sh\n"),
    ],
)
def test_every_comment_language_is_read(tmp_path, rel, text):
    root = _corpus(tmp_path, {rel: text})
    assert [r for r, _, _ in _found(root)] and all(r == rel for r, _, _ in _found(root))


@pytest.mark.parametrize(
    ("rel", "text"),
    [
        ("a.yaml", b"# globbed: tool/*.sh and tool/check-*.sh\n"),
        ("a.yaml", b"# template: scripts/<name>.py and tools/{a,b}.sh and tool/${X}.sh\n"),
        ("a.yaml", b"# tool/check-old.sh was renamed long ago\n"),
        ("a.yaml", b"# the guard formerly lived in tool/check-old.sh\n"),
        ("a.yaml", b"# lib/tool/x.sh is a nested path, not a repo-root one\n"),
        ("a.yaml", b"key: tool/gone.sh  # not a whole-line comment\n"),
        ("mod.py", b'X = "# tool/gone.sh"  # the string is code, not a comment\n'),
        ("a.md", b"# tool/gone.sh in a file type this gate does not read\n"),
        ("tool/notes", b"no shebang: tool/gone.sh\n"),
    ],
)
def test_patterns_history_and_non_comments_are_not_reported(tmp_path, rel, text):
    root = _corpus(tmp_path, {rel: text, "keep.sh": b"echo\n"})
    assert _found(root) == []


def test_a_directory_path_counts_when_it_exists(tmp_path):
    root = _corpus(tmp_path, {"a.sh": b"# everything under tool/meta/ and scripts/missing/\n", "tool/meta/x.py": b"x = 1\n"})
    assert [m for _, _, m in _found(root)] == ["names `scripts/missing`, which does not exist under the repo root"]


def test_custom_roots(tmp_path):
    root = _corpus(tmp_path, {"a.sh": b"# bin/gone.sh and tool/gone.sh\n"})
    found = find_comment_repo_path_problems(root, roots=("bin",), use_git=False)
    assert [f.message for f in found] == ["names `bin/gone.sh`, which does not exist under the repo root"]


def test_explicit_files(tmp_path):
    root = _corpus(tmp_path, {"a.sh": b"# tool/gone.sh\n", "b.sh": b"# tool/other_gone.sh\n"})
    found = find_comment_repo_path_problems(root, files=[root / "b.sh"])
    assert [(f.path, f.message) for f in found] == [("b.sh", "names `tool/other_gone.sh`, which does not exist under the repo root")]


def test_a_bom_prefixed_file_is_reported_like_the_plain_one(tmp_path):
    plain = _found(_corpus(tmp_path / "plain", {"pubspec.yaml": PUBSPEC}))
    bom = _found(_corpus(tmp_path / "bom", {"pubspec.yaml": BOM + PUBSPEC}))
    assert bom == plain and len(plain) == 1


def test_an_unparsable_file_fails_by_name_unless_allowed(tmp_path):
    root = _corpus(tmp_path, {"broken.py": b"def broken(:\n", "ok.sh": b"# fine\n"})
    assert [(f.path, f.rule) for f in find_comment_repo_path_problems(root, use_git=False)] == [("broken.py", "unparsed-file")]
    with pytest.raises(BaseException, match=r"broken.py"):
        assert_comment_repo_paths(root, use_git=False)
    assert_comment_repo_paths(root, use_git=False, allow_unparsed=True)


def test_an_empty_corpus_fails_the_floor(tmp_path):
    root = _corpus(tmp_path, {"README.md": b"# tool/gone.sh\n"})
    with pytest.raises(BaseException, match="expected at least 1"):
        assert_comment_repo_paths(root, use_git=False)
